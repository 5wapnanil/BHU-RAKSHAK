"""Unit tests for Phase 2D Scientific Annotation Protocol and Validation.

Verifies:
1. Validation of annotation schema and controlled vocabularies.
2. Detection of missing candidates and hash mismatches.
3. Detection of duplicate annotation records (same candidate, annotator, version).
4. Strict prohibition of AI models/bots as human annotators (AIAnnotatorProhibitedError).
5. State transition consistency (e.g. 'adjudicated' requires label, 'pending_review' cannot have label).
6. Site and series leakage prevention across evaluation splits.
7. Generation of clean annotation templates with non-label metadata.
8. Path traversal and unsafe file path guards.
"""

import csv
from pathlib import Path
import tempfile
import unittest

from backend.app.services.vlm_evaluation import (
    AIAnnotatorProhibitedError,
    ALLOWED_ANNOTATION_QUALITIES,
    ALLOWED_CONFIDENCE_LEVELS,
    ALLOWED_REVIEW_STATUSES,
    ALLOWED_REVIEWER_LABELS,
    AnnotationIntegrityError,
    AnnotationRecord,
    AnnotationValidator,
    CONTROLLED_OBSERVABLE_INDICATORS,
    DataLeakageError,
    VLMEvaluationHarness,
    VLMEvaluationSample,
)


class TestAnnotationProtocol(unittest.TestCase):
    """Test suite for annotation protocol, schema enforcement, and split safety."""

    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.test_dir = Path(self.temp_dir.name)

    def tearDown(self):
        self.temp_dir.cleanup()

    def test_valid_annotation_record(self):
        """Verify that a compliant human annotation record passes validation."""
        rec = AnnotationRecord(
            candidate_id="CAND_001",
            image_sha256="abc123def456",
            annotator_id="GEOTECH_EXPERT_01",
            annotation_version="v1.0",
            observable_indicators=["fresh_scarp", "tension_cracks"],
            image_quality="high_resolution",
            reviewer_label="critical",
            confidence="certain",
            evidence_notes="Visible scarp displacement along road cut.",
            review_status="completed",
            reviewed_at="2026-10-23T10:00:00Z",
        )
        known = {"CAND_001": "abc123def456"}
        errors = AnnotationValidator.validate_record(rec, known_candidates=known)
        self.assertEqual(errors, [])

    def test_prohibits_ai_model_annotator_spoofing(self):
        """Verify that AI model names cannot be passed off as human annotators."""
        prohibited_ids = ["gemma3:4b", "gemini-3.5-flash", "ollama_local", "ai_bot", "model_v1"]
        for bad_id in prohibited_ids:
            rec = AnnotationRecord(
                candidate_id="CAND_001",
                image_sha256="abc123def456",
                annotator_id=bad_id,
                annotation_version="v1.0",
                observable_indicators=["rockfall_debris"],
                image_quality="adequate",
                reviewer_label="high",
                confidence="probable",
                evidence_notes="Generated by model",
                review_status="completed",
                reviewed_at="2026-10-23T10:00:00Z",
            )
            with self.assertRaises(AIAnnotatorProhibitedError):
                AnnotationValidator.validate_record(rec)

    def test_nonexistent_candidate_flagged(self):
        """Verify that annotation referencing an unknown candidate ID is flagged."""
        rec = AnnotationRecord(
            candidate_id="CAND_NONEXISTENT",
            image_sha256="abc123def456",
            annotator_id="EXPERT_01",
            annotation_version="v1.0",
            observable_indicators=[],
            image_quality="adequate",
            reviewer_label="low",
            confidence="probable",
            evidence_notes="",
            review_status="completed",
            reviewed_at="2026-10-23T10:00:00Z",
        )
        known = {"CAND_001": "abc123def456"}
        errors = AnnotationValidator.validate_record(rec, known_candidates=known)
        self.assertTrue(any("does not exist" in e for e in errors))

    def test_hash_mismatch_flagged(self):
        """Verify that hash mismatch between annotation and candidate manifest is caught."""
        rec = AnnotationRecord(
            candidate_id="CAND_001",
            image_sha256="wrong_hash_12345",
            annotator_id="EXPERT_01",
            annotation_version="v1.0",
            observable_indicators=[],
            image_quality="adequate",
            reviewer_label="low",
            confidence="probable",
            evidence_notes="",
            review_status="completed",
            reviewed_at="2026-10-23T10:00:00Z",
        )
        known = {"CAND_001": "real_hash_67890"}
        errors = AnnotationValidator.validate_record(rec, known_candidates=known)
        self.assertTrue(any("Hash mismatch" in e for e in errors))

    def test_adjudicated_status_requires_label(self):
        """Verify that an adjudicated annotation cannot have an empty or pending label."""
        rec = AnnotationRecord(
            candidate_id="CAND_001",
            image_sha256="abc123def456",
            annotator_id="LEAD_ADJUDICATOR",
            annotation_version="v1.0",
            observable_indicators=[],
            image_quality="adequate",
            reviewer_label="",
            confidence="certain",
            evidence_notes="",
            review_status="adjudicated",
            reviewed_at="2026-10-23T10:00:00Z",
        )
        errors = AnnotationValidator.validate_record(rec)
        self.assertTrue(any("reviewer_label is empty" in e for e in errors))

    def test_pending_review_cannot_have_determinate_label(self):
        """Verify that pending_review cannot prematurely encode a determinate hazard label."""
        rec = AnnotationRecord(
            candidate_id="CAND_001",
            image_sha256="abc123def456",
            annotator_id="",
            annotation_version="v1.0",
            observable_indicators=[],
            image_quality="adequate",
            reviewer_label="critical",  # premature label
            confidence="",
            evidence_notes="",
            review_status="pending_review",
            reviewed_at="",
        )
        errors = AnnotationValidator.validate_record(rec)
        self.assertTrue(any("non-empty label" in e for e in errors))

    def test_duplicate_annotation_records_detected(self):
        """Verify that multiple records for the same candidate, annotator, and version are rejected."""
        csv_path = self.test_dir / "dups.csv"
        csv_content = """candidate_id,image_sha256,annotator_id,annotation_version,observable_indicators,image_quality,reviewer_label,confidence,evidence_notes,review_status,reviewed_at
CAND_001,hash1,EXPERT_A,v1.0,fresh_scarp,high_resolution,critical,certain,note,completed,2026-10-23T10:00:00Z
CAND_001,hash1,EXPERT_A,v1.0,fresh_scarp,high_resolution,critical,certain,note2,completed,2026-10-23T10:05:00Z
"""
        csv_path.write_text(csv_content, encoding="utf-8")
        records, errors = AnnotationValidator.load_and_validate_annotations_csv(csv_path)
        self.assertTrue(any("Duplicate annotation record" in e for e in errors))

    def test_site_leakage_prevented_across_splits(self):
        """Verify that samples with identical duplicate_group_id / event_site_group cannot cross splits."""
        sample_train = VLMEvaluationSample(
            image_id="IMG_01",
            image_sha256="hash_01",
            image_path=str(self.test_dir / "img1.jpg"),
            source="Test",
            license_reference="CC-BY-4.0",
            split="train",
            duplicate_group_id="GPS_41.7_44.76",
        )
        sample_test = VLMEvaluationSample(
            image_id="IMG_02",
            image_sha256="hash_02",
            image_path=str(self.test_dir / "img2.jpg"),
            source="Test",
            license_reference="CC-BY-4.0",
            split="test",
            duplicate_group_id="GPS_41.7_44.76",  # same site!
        )
        with self.assertRaises(DataLeakageError):
            VLMEvaluationHarness.validate_split_integrity([sample_train, sample_test])

    def test_unknown_event_site_allowed_across_splits(self):
        """Verify that generic UNKNOWN_EVENT_OR_SITE markers do not falsely trigger leakage."""
        sample_train = VLMEvaluationSample(
            image_id="IMG_03",
            image_sha256="hash_03",
            image_path=str(self.test_dir / "img3.jpg"),
            source="Test",
            license_reference="CC-BY-4.0",
            split="train",
            duplicate_group_id="UNKNOWN_EVENT_OR_SITE",
        )
        sample_test = VLMEvaluationSample(
            image_id="IMG_04",
            image_sha256="hash_04",
            image_path=str(self.test_dir / "img4.jpg"),
            source="Test",
            license_reference="CC-BY-4.0",
            split="test",
            duplicate_group_id="UNKNOWN_EVENT_OR_SITE",
        )
        # Should NOT raise DataLeakageError
        VLMEvaluationHarness.validate_split_integrity([sample_train, sample_test])

    def test_generate_blank_annotation_template(self):
        """Verify template generation preserves candidate references and blanks human reviews."""
        manifest_path = self.test_dir / "manifest.csv"
        manifest_content = """candidate_id,image_sha256,download_status
CAND_101,sha101,downloaded
CAND_102,sha102,skipped_unapproved
CAND_103,sha103,downloaded
"""
        manifest_path.write_text(manifest_content, encoding="utf-8")
        out_template = self.test_dir / "template.csv"

        count = AnnotationValidator.generate_blank_annotation_template(
            candidates_manifest_path=manifest_path,
            output_template_path=out_template,
            annotation_version="v1.0",
            downloaded_only=True,
        )
        self.assertEqual(count, 2)  # only CAND_101 and CAND_103

        records, errors = AnnotationValidator.load_and_validate_annotations_csv(out_template)
        self.assertEqual(len(records), 2)
        self.assertEqual(errors, [])
        for r in records:
            self.assertEqual(r.review_status, "pending_review")
            self.assertEqual(r.reviewer_label, "")
            self.assertEqual(r.annotator_id, "")


if __name__ == "__main__":
    unittest.main()
